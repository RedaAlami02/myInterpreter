#!/usr/bin/env python3
"""Generate the mobile public-column allowlist from the shared market contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "myinterpreter_app/lib/market_columns.dart"


def generated():
    tables = json.loads((ROOT / "migrations/supabase/market_contract.json").read_text())["tables"]
    tables.update(json.loads((ROOT / "migrations/supabase/supplemental_contract.json").read_text())["tables"])
    lines = ["// Generated by tools/generate_flutter_market_contract.py. Do not edit.",
             "const publicMarketColumns = <String, List<String>>{"]
    for table, spec in tables.items():
        fields = ["id", *spec["fields"]]
        compact = f"  '{table}': [" + ", ".join(f"'{field}'" for field in fields) + "],"
        if len(compact) <= 80:
            lines.append(compact)
            continue
        lines.append(f"  '{table}': [")
        lines.extend(f"    '{field}'," for field in fields)
        lines.append("  ],")
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != expected:
            raise SystemExit("Mobile market columns need regeneration.")
        print("Mobile market columns match the shared contract.")
    else:
        DESTINATION.write_text(expected)
        print("Mobile market columns generated.")
